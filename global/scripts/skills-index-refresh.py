#!/usr/bin/env python3
"""Regenerate the automatic inventory block of ~/.claude/skills/INDEX.md.

Why: an index that lies costs more than no index, because it is what you consult before
concluding "I cannot do that" (a Skill Discovery rule). Hand-maintained indexes drift:
counts disagree with the disk and new skills never appear.

The editorial part of INDEX.md (navigation, commented categories) stays hand-written. This
script only touches the block delimited by the two markers below, and appends it at the end
of the file (creating INDEX.md if needed). Re-run after any skill or agent creation/removal.

Usage: python3 skills-index-refresh.py [--check]
  --check  do not write, exit 1 if the inventory block is out of date (for CI / hooks)
Environment: CLAUDE_DIR (default ~/.claude), SKILLS_EXCLUDE (comma-separated dir names to skip)
"""
import datetime
import os
import pathlib
import re
import sys

CLAUDE = pathlib.Path(os.environ.get("CLAUDE_DIR", str(pathlib.Path.home() / ".claude")))
SK = CLAUDE / "skills"
AG = CLAUDE / "agents"
EXCLUDE = {s.strip() for s in os.environ.get("SKILLS_EXCLUDE", "").split(",") if s.strip()}
BEGIN = "<!-- INVENTORY-AUTO:begin -->"
END = "<!-- INVENTORY-AUTO:end -->"


def desc(p):
    try:
        t = p.read_text(encoding="utf-8", errors="replace")
    except OSError as e:
        print("unreadable: %s (%s)" % (p, e), file=sys.stderr)
        return ""
    m = re.search(r"^description:\s*(.+)$", t, re.M)
    if not m:
        return ""
    d = m.group(1).strip().strip('"').strip("'")
    return (d[:157] + "...") if len(d) > 160 else d


def skills():
    out = {}
    for p in SK.glob("*.md"):
        if p.name != "INDEX.md":
            out[p.stem] = (desc(p), p.name)
    for p in sorted(SK.iterdir()):
        if p.is_dir() and p.name not in EXCLUDE and (p / "SKILL.md").exists():
            out.setdefault(p.name, (desc(p / "SKILL.md"), "%s/SKILL.md" % p.name))
    return out


def reference_files():
    """Thematic .md files stored in sub-folders (references, not invocable)."""
    out = {}
    for p in sorted(SK.rglob("*.md")):
        rel = p.relative_to(SK)
        if len(rel.parts) < 2 or rel.parts[0] in EXCLUDE:
            continue
        if rel.name in ("SKILL.md", "INDEX.md"):
            continue
        out[str(rel)] = desc(p)
    return out


def agents():
    if not AG.exists():
        return {}
    return {p.stem: desc(p) for p in sorted(AG.glob("*.md"))}


def build_block():
    c, r, a = skills(), reference_files(), agents()
    lines = [BEGIN,
             "## FULL INVENTORY (generated on %s)" % datetime.date.today().isoformat(),
             "",
             "> Generated by `python3 ~/.claude/scripts/skills-index-refresh.py`. Do not edit by hand.",
             "> Skills **%d** · reference files **%d** · agents **%d**" % (len(c), len(r), len(a)),
             "", "### Skills", "", "| Skill | File | Description |", "|---|---|---|"]
    for n in sorted(c):
        d, f = c[n]
        lines.append("| `/%s` | `%s` | %s |" % (n, f, d.replace("|", "/")))
    lines += ["", "### Reference files (not invocable)", "", "| File | Description |", "|---|---|"]
    for f in sorted(r):
        lines.append("| `%s` | %s |" % (f, r[f].replace("|", "/")))
    lines += ["", "### Agents (`~/.claude/agents/`)", "", "| Agent | Description |", "|---|---|"]
    for n in sorted(a):
        lines.append("| `%s` | %s |" % (n, a[n].replace("|", "/")))
    lines.append(END)
    return "\n".join(lines), (len(c), len(r), len(a))


def strip_date(block):
    return re.sub(r"\(generated on [\d-]+\)", "", block)


def main():
    check = "--check" in sys.argv[1:]
    if not SK.exists():
        print("no skills directory: %s" % SK, file=sys.stderr)
        return 1
    block, counts = build_block()
    idx = SK / "INDEX.md"
    text = idx.read_text(encoding="utf-8") if idx.exists() else "# Skills index\n"
    if BEGIN in text and END in text:
        old = re.search(re.escape(BEGIN) + r".*?" + re.escape(END), text, flags=re.S).group(0)
        new_text = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S)
        up_to_date = strip_date(old) == strip_date(block)
    else:
        new_text = text.rstrip() + "\n\n---\n\n" + block + "\n"
        up_to_date = False
    if check:
        print("INDEX.md %s" % ("up to date" if up_to_date else "OUT OF DATE"))
        return 0 if up_to_date else 1
    idx.write_text(new_text, encoding="utf-8")
    print("INDEX.md updated: %d skills, %d reference files, %d agents" % counts)
    return 0


if __name__ == "__main__":
    sys.exit(main())
