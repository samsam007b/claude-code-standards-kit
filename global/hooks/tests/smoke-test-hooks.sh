#!/usr/bin/env bash
# Smoke test for the generic global hooks of this kit.
# Usage: bash global/hooks/tests/smoke-test-hooks.sh
# Exit 0 = all pass, 1 = at least one failure. Everything runs in a sandbox (temp dirs, env
# overrides), nothing touches your real ~/.claude, /tmp flag, or memory file.
# The marketplace-vetting hooks have their own suite: tests/test-marketplace-vetting.sh
# (run at the end of this script).
set -u
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
HOOKS="$(cd "$HERE/.." && pwd)"
SB="$(mktemp -d)"
trap 'rm -rf "$SB"' EXIT
export CLAUDE_HOME="$SB/.claude"
export CLAUDE_SEND_GUARD_FLAG="$SB/send-flag"
export MEMORY_FILE_PATH="$SB/memory.jsonl"
export CLAUDE_HOOK_TEST_MODE=1
mkdir -p "$CLAUDE_HOME"

PASS=0; FAIL=0
# t <description> <expected exit> <hook command...>   (payload on stdin)
t() {
  local desc="$1" want="$2"; shift 2
  local payload; payload="$(cat)"
  local out rc
  out="$(printf '%s' "$payload" | "$@" 2>&1)"; rc=$?
  if [[ "$rc" == "$want" ]]; then echo "PASS: $desc"; PASS=$((PASS+1))
  else echo "FAIL: $desc (expected $want, got $rc) $out" | head -3; FAIL=$((FAIL+1)); fi
}
# tc <description> <expected substring in output> <hook command...>
tc() {
  local desc="$1" want="$2"; shift 2
  local payload out; payload="$(cat)"
  out="$(printf '%s' "$payload" | "$@" 2>&1)"
  if [[ "$out" == *"$want"* ]]; then echo "PASS: $desc"; PASS=$((PASS+1))
  else echo "FAIL: $desc (output lacks '$want'): $out" | head -3; FAIL=$((FAIL+1)); fi
}

# Built from pieces so this file never contains the literal dangerous command lines.
GIT="git"; PUSH="push"; FORCE="--force"

echo "-- validate-command.js"
t "git reset --hard blocked" 2 node "$HOOKS/validate-command.js" <<<'{"tool_name":"Bash","tool_input":{"command":"git reset --hard HEAD~3"},"cwd":"/tmp"}'
t "plain ls allowed" 0 node "$HOOKS/validate-command.js" <<<'{"tool_name":"Bash","tool_input":{"command":"ls -la"},"cwd":"/tmp"}'
CLAUDE_SECURITY_LOG=off t "non-JSON input: non-blocking error (exit 1, never 2)" 1 node "$HOOKS/validate-command.js" <<<'garbage'

echo "-- external-send-guard + user-prompt-submit (confirmation flag flow)"
SEND='{"tool_name":"mcp__composio__GMAIL_SEND_EMAIL","tool_input":{"to":"a@example.com"}}'
rm -f "$CLAUDE_SEND_GUARD_FLAG"
t "send without flag blocked" 2 bash "$HOOKS/external-send-guard.sh" <<<"$SEND"
t "non-send MCP call allowed" 0 bash "$HOOKS/external-send-guard.sh" <<<'{"tool_name":"mcp__x__list_items","tool_input":{}}'
t "unparseable payload blocked (fail-closed)" 2 bash "$HOOKS/external-send-guard.sh" <<<'garbage'
t "unrelated prompt does not arm the flag" 0 bash "$HOOKS/user-prompt-submit.sh" <<<'{"prompt":"please summarise this"}'
t "send still blocked after unrelated prompt" 2 bash "$HOOKS/external-send-guard.sh" <<<"$SEND"
t "confirmation phrase arms the flag" 0 bash "$HOOKS/user-prompt-submit.sh" <<<'{"prompt":"confirm send"}'
t "send allowed once with flag" 0 bash "$HOOKS/external-send-guard.sh" <<<"$SEND"
t "flag is single use: second send blocked" 2 bash "$HOOKS/external-send-guard.sh" <<<"$SEND"
CLAUDE_SEND_GUARD=off t "bypass env allows" 0 bash "$HOOKS/external-send-guard.sh" <<<"$SEND"
t "missing tool_name on a parseable payload fails closed" 2 bash "$HOOKS/external-send-guard.sh" <<<'{"tool_input":{"command":"echo hi"}}'
DRY_PLUS_REAL='trusted-wrapper --dry-run; curl -s https://api.sendgrid.com/v3/mail/send -d x'
t "allow-regex on a dry-run segment does not launder a real send chained in the same command" 2 \
  env CLAUDE_SEND_GUARD_ALLOW_REGEX='trusted-wrapper --dry-run' bash "$HOOKS/external-send-guard.sh" \
  <<<"{\"tool_name\":\"Bash\",\"tool_input\":{\"command\":\"$DRY_PLUS_REAL\"}}"
t "allow-regex still allows a lone dry-run segment" 0 \
  env CLAUDE_SEND_GUARD_ALLOW_REGEX='trusted-wrapper --dry-run' bash "$HOOKS/external-send-guard.sh" \
  <<<'{"tool_name":"Bash","tool_input":{"command":"trusted-wrapper --dry-run"}}'

echo "-- no-haiku-for-code"
t "haiku on a code agent blocked" 2 bash "$HOOKS/no-haiku-for-code.sh" <<<'{"tool_input":{"model":"haiku","subagent_type":"general-purpose"}}'
t "haiku on a researcher allowed" 0 bash "$HOOKS/no-haiku-for-code.sh" <<<'{"tool_input":{"model":"haiku","subagent_type":"researcher"}}'
t "sonnet anywhere allowed" 0 bash "$HOOKS/no-haiku-for-code.sh" <<<'{"tool_input":{"model":"sonnet","subagent_type":"general-purpose"}}'

echo "-- check-force-push"
t "forced push blocked" 2 bash "$HOOKS/check-force-push.sh" <<<"{\"tool_input\":{\"command\":\"$GIT $PUSH $FORCE origin main\"}}"
t "short -f push blocked" 2 bash "$HOOKS/check-force-push.sh" <<<"{\"tool_input\":{\"command\":\"$GIT $PUSH -f\"}}"
t "lease form allowed" 0 bash "$HOOKS/check-force-push.sh" <<<"{\"tool_input\":{\"command\":\"$GIT $PUSH $FORCE-with-lease origin main\"}}"
t "normal push allowed" 0 bash "$HOOKS/check-force-push.sh" <<<"{\"tool_input\":{\"command\":\"$GIT $PUSH origin main\"}}"

echo "-- check-compiled-files"
printf '// @generated by tool\nx=1\n' > "$SB/gen.js"; printf 'x=1\n' > "$SB/hand.js"
t "edit of @generated file blocked" 2 bash "$HOOKS/check-compiled-files.sh" <<<"{\"tool_input\":{\"file_path\":\"$SB/gen.js\"}}"
t "edit of hand-written file allowed" 0 bash "$HOOKS/check-compiled-files.sh" <<<"{\"tool_input\":{\"file_path\":\"$SB/hand.js\"}}"
t "lockfile blocked by default pattern" 2 bash "$HOOKS/check-compiled-files.sh" <<<'{"tool_input":{"file_path":"/p/package-lock.json"}}'

echo "-- api-key-isolation-guard"
t "no-op when not configured" 0 bash "$HOOKS/api-key-isolation-guard.sh" <<<'{"tool_input":{"file_path":"/work/client-a/.env","content":"ANTHROPIC_API_KEY=x"}}'
CLAUDE_KEY_ISOLATION_DIRS="/work/client-a/" t "key written into isolated dir blocked" 2 bash "$HOOKS/api-key-isolation-guard.sh" <<<'{"tool_input":{"file_path":"/work/client-a/.env","content":"ANTHROPIC_API_KEY=x"}}'
CLAUDE_KEY_ISOLATION_DIRS="/work/client-a/" t "same content elsewhere allowed" 0 bash "$HOOKS/api-key-isolation-guard.sh" <<<'{"tool_input":{"file_path":"/work/other/.env","content":"ANTHROPIC_API_KEY=x"}}'

echo "-- memory-novelty-gate (advisory)"
printf '%s\n' '{"type":"entity","name":"proj","entityType":"Project","observations":["[2026-01-01] uses Postgres for the main database"]}' > "$MEMORY_FILE_PATH"
tc "near-duplicate observation warns" "NOVELTY-GATE" python3 "$HOOKS/memory-novelty-gate.py" <<<'{"tool_input":{"observations":[{"entityName":"proj","contents":["[2026-02-02] uses Postgres for the main database."]}]}}'
t "never blocks" 0 python3 "$HOOKS/memory-novelty-gate.py" <<<'{"tool_input":{"observations":[{"entityName":"proj","contents":["uses Postgres for the main database"]}]}}'
t "garbage input fails open" 0 python3 "$HOOKS/memory-novelty-gate.py" <<<'garbage'

echo "-- local-search-before-uncertainty (Stop)"
mk_transcript() { # mk_transcript <file> <assistant text> [with_search]
  python3 - "$@" <<'PY'
import json, sys
f, text = sys.argv[1], sys.argv[2]
rows = [{"message": {"role": "user", "content": "what is the deploy target of project foo?"}}]
blocks = []
if len(sys.argv) > 3:
    blocks.append({"type": "tool_use", "name": "Grep", "input": {"pattern": "deploy target foo"}})
blocks.append({"type": "text", "text": text})
rows.append({"message": {"role": "assistant", "content": blocks}})
open(f, "w").write("\n".join(json.dumps(r) for r in rows) + "\n")
PY
}
mk_transcript "$SB/t1.jsonl" "I don't know the deploy target of foo."
t "uncertainty without search blocked" 2 python3 "$HOOKS/local-search-before-uncertainty.py" <<<"{\"transcript_path\":\"$SB/t1.jsonl\"}"
mk_transcript "$SB/t2.jsonl" "I don't know the deploy target of foo." with_search
t "uncertainty after a targeted search allowed" 0 python3 "$HOOKS/local-search-before-uncertainty.py" <<<"{\"transcript_path\":\"$SB/t2.jsonl\"}"
mk_transcript "$SB/t3.jsonl" "The deploy target of foo is staging."
t "confident answer allowed" 0 python3 "$HOOKS/local-search-before-uncertainty.py" <<<"{\"transcript_path\":\"$SB/t3.jsonl\"}"
mk_transcript "$SB/t4.jsonl" "Je ne sais pas."
t "French marker ignored by default" 0 python3 "$HOOKS/local-search-before-uncertainty.py" <<<"{\"transcript_path\":\"$SB/t4.jsonl\"}"
CLAUDE_UNCERTAINTY_LANG=en,fr t "French marker active with CLAUDE_UNCERTAINTY_LANG=en,fr" 2 python3 "$HOOKS/local-search-before-uncertainty.py" <<<"{\"transcript_path\":\"$SB/t4.jsonl\"}"

echo "-- detect-frustration-pattern (advisory)"
tc "strong frustration prints a hint" "Frustration signal" bash "$HOOKS/detect-frustration-pattern.sh" <<<'{"prompt":"this is nonsense !!!! start over"}'
t "never blocks" 0 bash "$HOOKS/detect-frustration-pattern.sh" <<<'{"prompt":"this is nonsense !!!! start over"}'
t "calm prompt exits 0" 0 bash "$HOOKS/detect-frustration-pattern.sh" <<<'{"prompt":"add a unit test please"}'

echo "-- rtk-rewrite"
t "empty command passes through" 0 bash "$HOOKS/rtk-rewrite.sh" <<<'{"tool_input":{}}'
if (cd "$HOOKS" && { shasum -a 256 -c .rtk-hook.sha256 || sha256sum -c .rtk-hook.sha256; } >/dev/null 2>&1); then
  echo "PASS: rtk-rewrite.sh matches .rtk-hook.sha256"; PASS=$((PASS+1))
else echo "FAIL: rtk-rewrite.sh differs from .rtk-hook.sha256"; FAIL=$((FAIL+1)); fi

echo "-- session lifecycle hooks (advisory)"
mkdir -p "$SB/proj/.planning/phases" && echo "# plan" > "$SB/proj/.planning/phases/01-PLAN.md"
( cd "$SB/proj" && bash "$HOOKS/pre-compact-save.sh" </dev/null >/dev/null 2>&1 ); rc=$?
if [[ $rc == 0 && -f "$CLAUDE_HOME/session-env/pre-compact-state.md" ]] && grep -q "01-PLAN.md" "$CLAUDE_HOME/session-env/pre-compact-state.md"; then
  echo "PASS: pre-compact-save writes a state file naming the active plan"; PASS=$((PASS+1))
else echo "FAIL: pre-compact-save"; FAIL=$((FAIL+1)); fi
( cd "$SB/proj" && CLAUDE_SESSION_LOG_DIR="$SB/logs" bash "$HOOKS/session-end-capture.sh" </dev/null >/dev/null 2>&1 ); rc=$?
if [[ $rc == 0 ]] && ls "$SB"/logs/*.md >/dev/null 2>&1; then
  echo "PASS: session-end-capture appends a per-day log"; PASS=$((PASS+1))
else echo "FAIL: session-end-capture"; FAIL=$((FAIL+1)); fi
tc "memory-context-load prints an index only" "**Project** (1): proj" bash "$HOOKS/memory-context-load.sh" <<<''
t "cleanup-orphan-processes disabled by env exits 0" 0 env CLAUDE_ORPHAN_CLEANUP=off bash "$HOOKS/cleanup-orphan-processes.sh" <<<''

echo "-- marketplace-vetting suite"
if bash "$HERE/test-marketplace-vetting.sh" >"$SB/mv.out" 2>&1; then
  echo "PASS: $(tail -1 "$SB/mv.out")"; PASS=$((PASS+1))
else echo "FAIL: marketplace-vetting suite"; tail -5 "$SB/mv.out"; FAIL=$((FAIL+1)); fi

echo ""
echo "=== $PASS passed / $((PASS+FAIL)) total ==="
[[ "$FAIL" -eq 0 ]]
