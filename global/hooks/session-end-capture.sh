#!/usr/bin/env bash
# SessionEnd hook: session-end-capture   (ADVISORY, never blocks)
#
# Appends a short entry to a per-day log file when a session ends, with a checklist of lessons
# to dispatch (a rule to add to CLAUDE.md, a memory note, a decision record, a reusable pattern).
# The point is to force the "what did you learn?" question at the one moment it is cheap to ask.
#
# Event / matcher : SessionEnd (no matcher)             (timeout 5)
# Exit codes      : always 0.
# Env:
#   CLAUDE_SESSION_LOG_DIR   directory for the per-day logs (default $HOME/.claude/session-logs)
#   CLAUDE_SESSION_NOTIFY=1  also show a desktop notification (macOS osascript or Linux notify-send)
#   CLAUDE_SESSION_CAPTURE=off   disable the hook

[[ "${CLAUDE_SESSION_CAPTURE:-on}" == "off" ]] && exit 0

DATE="$(date +%Y-%m-%d)"
HOUR="$(date +%H:%M)"
LOG_DIR="${CLAUDE_SESSION_LOG_DIR:-$HOME/.claude/session-logs}"
LOG_FILE="$LOG_DIR/$DATE.md"

mkdir -p "$LOG_DIR" 2>/dev/null || exit 0

if [[ ! -f "$LOG_FILE" ]]; then
  {
    echo "# Session log: $DATE"
    echo
    echo "> Generated by session-end-capture.sh"
    echo
  } > "$LOG_FILE"
fi

cat >> "$LOG_FILE" <<EOF
## Session $HOUR in $PWD

**Project**: $(basename "$PWD")

### What worked
- [fill in by hand]

### Lessons to dispatch
- [ ] Rule to add to CLAUDE.md?
- [ ] Feedback to save to memory?
- [ ] Decision record to write?
- [ ] Reusable pattern?

---

EOF

if [[ "${CLAUDE_SESSION_NOTIFY:-0}" == "1" ]]; then
  MSG="Session logged in $DATE.md"
  if command -v osascript >/dev/null 2>&1; then
    osascript -e "display notification \"$MSG\" with title \"Session End\"" 2>/dev/null || true
  elif command -v notify-send >/dev/null 2>&1; then
    notify-send "Session End" "$MSG" 2>/dev/null || true
  fi
fi

exit 0
